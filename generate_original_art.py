def post_process(i,im):
    rng=random.Random(i*1133)
    if i == 9:
        # true pixel blocks instead of smooth filtered SVG
        im=im.resize((80,55),Image.Resampling.NEAREST).resize((W,H),Image.Resampling.NEAREST)
    if i in {7,24,27,28,34,36,39,40,70,73,89}:
        # soft paper/watercolor wash, without external imagery
        smooth=im.filter(ImageFilter.GaussianBlur(2.5 if i in {7,73} else 1.6))
        im=Image.blend(im,smooth,.35 if i!=28 else .25)
    if i in {15,28,36,48,70,73,82}:
        glow=im.filter(ImageFilter.GaussianBlur(7))
        im=Image.blend(im,glow,.17)
    if i in {8,10,16,21,33,59,66,75,78,86,94}:
        im=ImageEnhance.Contrast(im).enhance(1.08)
    if i == 10:
        im=ImageEnhance.Color(im).enhance(.04)
    if i in {25,26,54,69,79,86,89}:
        im=ImageEnhance.Color(im).enhance(.78)
    if i in {43,90,95,96}:
        im=ImageEnhance.Contrast(im).enhance(1.15)
    # Efficient deterministic, subtle drawn-in-paper grain. Only output is generated original art.
    if i in {7,8,16,17,20,21,24,25,26,27,30,31,33,39,41,42,59,63,69,75,79,86,87,89,90,91,93}:
        p=im.load(); count=6200 if i in {21,59,75,86} else 2600
