def star(cx,cy,outer=22,inner=9,n=5,phase=-math.pi/2):
    pts=[]
    for k in range(n*2):
        r=outer if k%2==0 else inner
        t=phase+k*math.pi/n
        pts.append(f'{cx+math.cos(t)*r:.1f},{cy+math.sin(t)*r:.1f}')
    return ' '.join(pts)

def circle(cx,cy,r,fill,stroke='none',sw=0,extra=''):
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" {extra}/>'

def path(d,fill,stroke='none',sw=0,extra=''):
    return f'<path d="{d}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round" {extra}/>'

def ellipse(cx,cy,rx,ry,fill,stroke='none',sw=0,extra=''):
    return f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" {extra}/>'

def rect(x,y,w,h,fill,stroke='none',sw=0,rx=0,extra=''):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" {extra}/>'

def line(x1,y1,x2,y2,st,sw=2,extra=''):
    return f'<path d="M{x1},{y1} L{x2},{y2}" fill="none" stroke="{st}" stroke-width="{sw}" stroke-linecap="round" {extra}/>'

